/* One-time helper: download the Spyglass Lab fonts from Google Fonts (SIL Open Font License), latin and latin-ext only,
   and write them as embedded @font-face rules to fonts.css, so the page loads nothing from other servers.
   Fraunces (headings) and Figtree (text). Run: node getfonts.js */
const fs = require("fs"), https = require("https");
const URL = "https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,600;9..144,800&family=Figtree:wght@400;600;800&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
const get = (u) => new Promise((ok, no) => https.get(u, { headers: { "User-Agent": UA } }, (r) => { const b = []; r.on("data", (c) => b.push(c)); r.on("end", () => r.statusCode === 200 ? ok(Buffer.concat(b)) : no(new Error(u + " " + r.statusCode))); }).on("error", no));
(async () => {
  const css = (await get(URL)).toString();
  const blocks = css.split(/(?=\/\* [a-z-]+ \*\/)/).filter((b) => /^\/\* (latin|latin-ext) \*\//.test(b));
  /* Google lists one @font-face per weight, all pointing at the same variable font file. Merge them into one face per file
     with a weight range, so each file is embedded once. */
  const byUrl = {};
  for (const b of blocks) { const u = /url\((https:[^)]+\.woff2)\)/.exec(b)[1], w = +/font-weight:\s*(\d+)/.exec(b)[1]; (byUrl[u] = byUrl[u] || { b, ws: [] }).ws.push(w); }
  const cache = {}; let out = "/* Fraunces and Figtree, SIL Open Font License 1.1, from Google Fonts (latin, latin-ext). Generated by getfonts.js. */\n";
  for (const [u, { b, ws }] of Object.entries(byUrl)) {
    cache[u] = (await get(u)).toString("base64");
    out += b.replace(/font-weight:\s*\d+/, `font-weight: ${Math.min(...ws)} ${Math.max(...ws)}`).replace(/url\([^)]+\)\s*format\('woff2'\)/, `url(data:font/woff2;base64,${cache[u]}) format('woff2')`).trim() + "\n";
  }
  fs.writeFileSync(__dirname + "/fonts.css", out);
  console.log("faces:", blocks.length, "files:", Object.keys(cache).length, "KB:", (out.length / 1024).toFixed(0));
})();
